"""The tfy-platform-mcp tool list: a committed snapshot, and the references generated from it.

    python scripts/tool_schemas.py fetch     # live tools/list -> tool-schemas/tfy-platform-mcp.json
    python scripts/tool_schemas.py render    # snapshot -> skills/references/tool-inputs-*.md

`fetch` needs ASK_TFY_HOST, ASK_TFY_TENANT and TFY_API_KEY (evals/runner/.env). Run it when the
server's tools change, then `render`, and commit both. CI never reaches devtest: check_skills.py
fails when the rendered files do not match the snapshot, or a skill names a tool it lacks.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

import httpx

ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "tool-schemas" / "tfy-platform-mcp.json"
REFERENCES = ROOT / "skills" / "references"
PREFIX = "tool-inputs-"
FILE_BUDGET = 8_000
PAGING = {"limit", "offset"}
ENUM_SHOWN = 12


def fetch() -> list[dict]:
    url = f"{os.environ['ASK_TFY_HOST'].rstrip('/')}/api/svc/{os.environ['ASK_TFY_TENANT']}/mcp"
    headers = {
        "Authorization": f"Bearer {os.environ['TFY_API_KEY']}",
        "Accept": "application/json, text/event-stream",
    }
    tools: list[dict] = []
    cursor = None
    with httpx.Client(timeout=60) as client:
        while True:
            body = {"jsonrpc": "2.0", "id": 1, "method": "tools/list", "params": {"cursor": cursor} if cursor else {}}
            response = client.post(url, headers=headers, json=body)
            response.raise_for_status()
            text = response.text
            if "data:" in text[:20] or text.startswith("event:"):
                text = [line[5:] for line in text.splitlines() if line.startswith("data:")][-1]
            payload = json.loads(text)
            if "error" in payload:
                raise SystemExit(f"tools/list failed: {payload['error']}")
            tools += payload["result"]["tools"]
            cursor = payload["result"].get("nextCursor")
            if not cursor:
                return sorted(tools, key=lambda tool: tool["name"])


def load() -> list[dict]:
    return json.loads(SNAPSHOT.read_text())


def tool_names() -> set[str]:
    return {tool["name"] for tool in load()}


def _type(schema: dict) -> str:
    if schema.get("enum"):
        values = [str(v) for v in schema["enum"] if v is not None]
        shown = "|".join(values[:ENUM_SHOWN])
        return shown + ("|…" if len(values) > ENUM_SHOWN else "")
    kinds = schema.get("type")
    kinds = [k for k in (kinds if isinstance(kinds, list) else [kinds]) if k and k != "null"]
    kind = "|".join(kinds)
    if kind == "array":
        item = _type(schema.get("items") or {})
        return f"array of {item}" if item else "array"
    return "" if kind == "string" else kind


def _param(name: str, schema: dict) -> str:
    kind = _type(schema)
    return f"`{name}`" + (f" ({kind})" if kind else "")


def line(tool: dict) -> str:
    schema = tool.get("inputSchema") or {}
    properties = schema.get("properties") or {}
    required = set(schema.get("required") or [])
    parts = []
    needed = [_param(n, s) for n, s in properties.items() if n in required]
    optional = [_param(n, s) for n, s in properties.items() if n not in required and n not in PAGING]
    if needed:
        parts.append("required: " + ", ".join(needed))
    if optional:
        parts.append("optional: " + ", ".join(optional))
    if PAGING & set(properties):
        parts.append("paged (`limit`, `offset`)")
    hints = tool.get("annotations") or {}
    write = "" if hints.get("readOnlyHint") else " **write**"
    return f"- `{tool['name']}`{write} — " + ("; ".join(parts) or "no inputs")


def render(tools: list[dict]) -> dict[str, str]:
    """File name -> content. Tools are split alphabetically so each file stays under the cap."""
    groups: list[list[str]] = [[]]
    names: list[list[str]] = [[]]
    for tool in tools:
        entry = line(tool)
        if groups[-1] and sum(len(e) + 1 for e in groups[-1]) + len(entry) > FILE_BUDGET:
            groups.append([])
            names.append([])
        groups[-1].append(entry)
        names[-1].append(tool["name"])
    files = {}
    for index, (entries, members) in enumerate(zip(groups, names), start=1):
        name = f"{PREFIX}{index}"
        files[f"{name}.md"] = "\n".join([
            "---",
            f"name: {name}",
            f"description: Inputs of every tfy-platform-mcp tool from `{members[0]}` to `{members[-1]}`, generated "
            "from the live schemas - names, required vs optional, types, allowed values. Read a tool's line "
            "before calling it instead of get_tool_info.",
            "---",
            "",
            "<!-- Generated by scripts/tool_schemas.py from tool-schemas/tfy-platform-mcp.json. Do not edit. -->",
            "",
            "Untyped inputs are strings. **write** marks tools that change something.",
            "",
            *entries,
            "",
        ])
    return files


def stale() -> list[str]:
    """Problems with the rendered files on disk, compared with the snapshot."""
    wanted = render(load())
    present = {p.name: p.read_text() for p in REFERENCES.glob(f"{PREFIX}*.md")}
    problems = [f"skills/references/{n} is out of date" for n in wanted if present.get(n) != wanted[n]]
    problems += [f"skills/references/{n} is no longer generated" for n in present if n not in wanted]
    return problems


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("fetch", "render"))
    args = parser.parse_args()
    if args.command == "fetch":
        SNAPSHOT.parent.mkdir(exist_ok=True)
        tools = fetch()
        SNAPSHOT.write_text(json.dumps(tools, indent=1, ensure_ascii=False) + "\n")
        print(f"{len(tools)} tools -> {SNAPSHOT.relative_to(ROOT)}")
        return
    for path in REFERENCES.glob(f"{PREFIX}*.md"):
        path.unlink()
    for name, content in render(load()).items():
        (REFERENCES / name).write_text(content)
        print(f"skills/references/{name}: {len(content.encode()):,} bytes")


if __name__ == "__main__":
    sys.exit(main())
